#!/usr/bin/env bash
# Writes the three winget manifests (version, installer, defaultLocale) for
# a release's Inno Setup installers, with hashes taken from its
# SHA256SUMS.txt. Used by .github/workflows/package-managers.yml, which
# uploads them as a run artifact and, with a token, submits them to
# microsoft/winget-pkgs.
#
#   scripts/render-winget.sh VERSION SHA256SUMS.txt OUT_DIR [OWNER/REPO] [YYYY-MM-DD]
#
# Files land in OUT_DIR/manifests/i/ItsCetla/TaDa/VERSION/, the layout
# winget-pkgs uses. OWNER/REPO defaults to ItsCetla/tada; the release date
# defaults to today (UTC).
set -euo pipefail

version=${1:?version}
sums=${2:?SHA256SUMS.txt}
out=${3:?out dir}
repo=${4:-ItsCetla/tada}
date=${5:-$(date -u +%F)}
version=${version#v}
base="https://github.com/$repo/releases/download/v$version"
id=ItsCetla.TaDa
schema=1.12.0
# Inno Setup registers the uninstaller under "<AppId>_is1". Keep in step
# with AppId in packaging/windows/tada.iss.
product_code='{5C7E2B4A-8D1F-4E36-9A2C-C3E7A1F0B9D4}_is1'

sha() {
	local name="tada_${version}_$1_Setup.exe" h
	h=$(awk -v f="$name" '$2 == f || $2 == "*" f { print $1; exit }' "$sums")
	[[ $h =~ ^[0-9a-f]{64}$ ]] || { echo "no sha256 for $name in $sums" >&2; exit 1; }
	echo "$h" | tr 'a-f' 'A-F'
}

amd64=$(sha Windows_x86_64)
arm64=$(sha Windows_arm64)

dir="$out/manifests/i/${id%%.*}/${id#*.}/$version"
mkdir -p "$dir"

cat >"$dir/$id.yaml" <<EOF
# Generated by scripts/render-winget.sh in $repo.
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.$schema.schema.json

PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: $schema
EOF

cat >"$dir/$id.installer.yaml" <<EOF
# Generated by scripts/render-winget.sh in $repo.
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.$schema.schema.json

PackageIdentifier: $id
PackageVersion: $version
InstallerLocale: en-US
InstallerType: inno
Scope: user
InstallModes:
- interactive
- silent
- silentWithProgress
InstallerSwitches:
  Custom: /CURRENTUSER
UpgradeBehavior: install
Commands:
- tada
ProductCode: '$product_code'
ReleaseDate: '$date'
AppsAndFeaturesEntries:
- DisplayName: Ta-Da
  Publisher: ItsCetla
  ProductCode: '$product_code'
Installers:
- Architecture: x64
  InstallerUrl: $base/tada_${version}_Windows_x86_64_Setup.exe
  InstallerSha256: $amd64
- Architecture: arm64
  InstallerUrl: $base/tada_${version}_Windows_arm64_Setup.exe
  InstallerSha256: $arm64
ManifestType: installer
ManifestVersion: $schema
EOF

cat >"$dir/$id.locale.en-US.yaml" <<EOF
# Generated by scripts/render-winget.sh in $repo.
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.$schema.schema.json

PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: ItsCetla
PublisherUrl: https://github.com/ItsCetla
PublisherSupportUrl: https://github.com/$repo/issues
PackageName: Ta-Da
PackageUrl: https://tada.cetla.dev/
License: FSL-1.1-MIT
LicenseUrl: https://github.com/$repo/blob/main/LICENSE.md
ShortDescription: Terminal coding agent that talks only to the model providers and MCP servers you configure.
Description: |-
  Ta-Da is a terminal coding agent forked from Charm's Crush. It talks to
  nobody but the model providers and MCP servers you configure: no
  telemetry, no update checks, web tools off by default. It can import an
  OpenCode setup.
Moniker: tada
Tags:
- ai
- cli
- coding-agent
- llm
- terminal
ReleaseNotesUrl: https://github.com/$repo/releases/tag/v$version
ManifestType: defaultLocale
ManifestVersion: $schema
EOF

echo "$dir"
