#!/usr/bin/env bash
# Prints the Homebrew formula (tada.rb) for a release, with the archive
# hashes taken from its SHA256SUMS.txt. Used by
# .github/workflows/package-managers.yml, which pushes the result to the
# tap repository as Formula/tada.rb.
#
#   scripts/render-homebrew.sh VERSION SHA256SUMS.txt [OWNER/REPO] >tada.rb
#
# OWNER/REPO is the GitHub repository with the releases (default
# ItsCetla/tada).
set -euo pipefail

version=${1:?version}
sums=${2:?SHA256SUMS.txt}
repo=${3:-ItsCetla/tada}
version=${version#v}
base="https://github.com/$repo/releases/download/v$version"

sha() {
	local name="tada_${version}_$1.tar.gz" h
	h=$(awk -v f="$name" '$2 == f || $2 == "*" f { print $1; exit }' "$sums")
	[[ $h =~ ^[0-9a-f]{64}$ ]] || { echo "no sha256 for $name in $sums" >&2; exit 1; }
	echo "$h"
}

darwin_arm64=$(sha Darwin_arm64)
darwin_amd64=$(sha Darwin_x86_64)
linux_arm64=$(sha Linux_arm64)
linux_amd64=$(sha Linux_x86_64)

cat <<EOF
# Generated by scripts/render-homebrew.sh in $repo. Do not edit by hand:
# the next release overwrites it.
class Tada < Formula
  desc "Terminal coding agent that talks only to the providers you configure"
  homepage "https://tada.cetla.dev/"
  version "$version"
  license "FSL-1.1-MIT"

  on_macos do
    on_arm do
      url "$base/tada_${version}_Darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/tada_${version}_Darwin_x86_64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/tada_${version}_Linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/tada_${version}_Linux_x86_64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "tada"
    man1.install "manpages/tada.1.gz"
    bash_completion.install "completions/tada.bash" => "tada"
    zsh_completion.install "completions/tada.zsh" => "_tada"
    fish_completion.install "completions/tada.fish"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/tada --version")
  end
end
EOF
